#pragma once

namespace rc_vehicle {

/**
 * @brief Признак пробуксовки ведущих колёс без датчика скорости колеса
 *        (LOS-385).
 *
 * Угол заноса EKF пробуксовку по прямой не видит: колёса крутятся, а корпус
 * не уходит вбок. Скорость EKF тоже не помогает: она заякорена на мотор-
 * модель, то есть на скорость колёс, и при пробуксовке растёт вместе с ними.
 *
 * Поэтому скорость корпуса здесь считается отдельно — интегралом продольного
 * показания акселерометра. Мотор-модель (скорость, которую дал бы газ без
 * проскальзывания) играет роль скорости колёс. Пока колёса держат, обе
 * скорости растут одинаково; при пробуксовке корпус отстаёт, и разница
 * относительно скорости колёс и есть доля проскальзывания.
 *
 * Интегрируется именно показание акселерометра, без вычета гравитации: это
 * сила тяги колёс, делённая на массу, и на склоне она та же, что на ровном.
 * Мотор-модель склона тоже не знает, так что обе стороны — «как на ровном».
 * С вычетом гравитации подъём в 2° выглядел бы как пробуксовка: корпус
 * разгоняется медленнее, чем мотор-модель (ревью PR #402). Поэтому и
 * GetGroundSpeedMs() — скорость «как на ровном»: в подъём выше настоящей,
 * под уклон ниже.
 *
 * Интеграл ускорения уходит от смещения акселерометра, поэтому он медленно
 * подтягивается к мотор-модели (kLeakTauS). Долгую установившуюся
 * пробуксовку детектор из-за этого со временем забывает; рывок газа на
 * скользком, ради которого он нужен, длится короче.
 */
class WheelspinDetector {
 public:
  /** Начать заново: корпус едет со скоростью колёс wheel_speed_ms. */
  void Reset(float wheel_speed_ms = 0.0f) noexcept;

  /**
   * @brief Один тик control loop.
   * @param wheel_speed_ms   Скорость мотор-модели [м/с].
   * @param wheel_target_ms  Установившаяся скорость мотор-модели на текущем
   *                         газе [м/с]: выше wheel_speed_ms — мотор разгоняет
   *                         колёса.
   * @param traction_accel_g Продольное показание акселерометра в осях
   *                         машины, без вычета гравитации [g].
   * @param dt_sec           Шаг [с]; при dt_sec <= 0 состояние не меняется.
   */
  void Update(float wheel_speed_ms, float wheel_target_ms,
              float traction_accel_g, float dt_sec) noexcept;

  /** Скорость корпуса «как на ровном» по интегралу тяги [м/с]. */
  [[nodiscard]] float GetGroundSpeedMs() const noexcept {
    return ground_speed_ms_;
  }

  /**
   * Доля проскальзывания вперёд: (колёса − корпус) / колёса, не меньше 0.
   * На малой скорости знаменатель не меньше kMinWheelSpeedMs, чтобы шум
   * на старте не давал ложных долей.
   */
  [[nodiscard]] float GetSlipRatio() const noexcept { return slip_ratio_; }

  /**
   * Мотор разгоняет колёса: до установившейся скорости больше
   * kMinDriveGapMs. Сорваться в пробуксовку колёса могут только так —
   * лишний момент сверх сцепления. На ровном ходу (разница меньше
   * kMinDriveGapMs в обе стороны) интеграл сбрасывается к колёсам, чтобы
   * смещение акселерометра не копилось в долю.
   */
  [[nodiscard]] bool IsDriving() const noexcept { return driving_; }

 private:
  /** Постоянная времени подтяжки интеграла к мотор-модели [с]. */
  static constexpr float kLeakTauS = 2.0f;
  /** Нижняя граница знаменателя доли проскальзывания [м/с]. */
  static constexpr float kMinWheelSpeedMs = 0.5f;
  /** Запас до установившейся скорости, при котором колёса разгоняются
   *  [м/с]: при τ = 0.9 с это ускорение колёс от ~0.2 м/с². */
  static constexpr float kMinDriveGapMs = 0.2f;

  float ground_speed_ms_{0.0f};
  float slip_ratio_{0.0f};
  bool driving_{false};
};

}  // namespace rc_vehicle
